const id = {
  bsonType: 'string',
  pattern: '^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-4[0-9a-fA-F]{3}-[89abAB][0-9a-fA-F]{3}-[0-9a-fA-F]{12}$',
};
const date = { bsonType: 'date' };
const text = (maxLength: number) => ({ bsonType: 'string', maxLength });
const integer = { bsonType: ['int', 'long', 'double'], minimum: 0, multipleOf: 1 };
const token = { bsonType: 'string', pattern: '^[a-f0-9]{64}$' };
const challenge = {
  bsonType: 'object',
  additionalProperties: false,
  required: ['token_hash', 'expires_at'],
  properties: { token_hash: token, expires_at: date },
};
const document = (required: string[], properties: Record<string, unknown>) => ({
  bsonType: 'object',
  additionalProperties: false,
  required,
  properties: { _id: id, ...properties },
});
